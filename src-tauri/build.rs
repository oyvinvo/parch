use std::env;
use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    println!("cargo:rerun-if-changed=../dist");

    let out_dir = env::var("OUT_DIR").unwrap();
    let dest_path = Path::new(&out_dir).join("embedded_assets.rs");

    let manifest_dir = env::var("CARGO_MANIFEST_DIR").unwrap();
    let dist_dir = Path::new(&manifest_dir).join("../dist");

    let mut match_arms = Vec::new();

    if dist_dir.join("index.html").exists() {
        let mut files = Vec::new();
        collect_files(&dist_dir, &dist_dir, &mut files);

        for (rel_path, abs_path) in files {
            let norm_rel = rel_path.replace('\\', "/");
            let abs_str = abs_path.to_str().unwrap().replace('\\', "/");
            match_arms.push(format!(
                "        {:?} => Some(include_bytes!({:?})),",
                norm_rel, abs_str
            ));
        }
    }

    let code = format!(
        r#"// Generated by build.rs - DO NOT EDIT MANUALLY
pub fn get_embedded_file(rel_path: &str) -> Option<&'static [u8]> {{
    match rel_path {{
{}
        _ => None,
    }}
}}
"#,
        match_arms.join("\n")
    );

    fs::write(dest_path, code).unwrap();
}

fn collect_files(root: &Path, current: &Path, list: &mut Vec<(String, PathBuf)>) {
    if let Ok(entries) = fs::read_dir(current) {
        for entry in entries.flatten() {
            let path = entry.path();
            if path.is_dir() {
                collect_files(root, &path, list);
            } else if path.is_file() {
                if let Ok(rel) = path.strip_prefix(root) {
                    list.push((rel.to_string_lossy().to_string(), path));
                }
            }
        }
    }
}
